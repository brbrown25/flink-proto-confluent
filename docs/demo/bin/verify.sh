#!/usr/bin/env bash
# verify.sh [--keep] [--no-build] [STEP...]  — runs the demo non-interactively and checks its output.
#
# Builds the format JAR from this checkout (./setup.sh), starts a clean demo stack, runs every cast
# script (casts/NAME.sh, with CAST_FAST=1) and stand-alone SQL file (sql/NAME.sql, through
# bin/flink-sql) in the order below, and fails when a step exits non-zero, prints a Flink SQL client
# error, or does not print the lines listed in expected/STEP.txt (in that order). A renamed or removed
# format option therefore fails it, as does a committed SQL file that no step runs.
#
#   STEP        a step name from STEPS below; default: all of them. Later steps rely on the topics
#               earlier ones create (write-back reads the orders quickstart writes).
#   --keep      leave the stack running afterwards (default: docker compose down -v)
#   --no-build  reuse the JARs already in ./lib instead of running ./setup.sh
#
# FLINK_VERSION=2.2 runs it on the Flink 2.2 stack (see setup.sh). STEP_TIMEOUT (seconds, default 300)
# bounds each step when a `timeout` command is available. Each step's output is kept in .verify/.
# The stack runs as compose project "proto-confluent-demo-verify" (override with COMPOSE_PROJECT_NAME),
# so it never touches a stack started by record.sh or by hand.
set -euo pipefail
cd "$(dirname "$0")/.."

STEPS="quickstart quickstart.sql write-back dead-letter breaking-change-dlq compat-modes schema-evolution"
# Steps that need a fresh stack: schema-evolution creates the orders topic itself and its read would
# also return the rows quickstart wrote there.
FRESH_STACK_STEPS="schema-evolution"
# Output that means a statement failed, whatever the step expects (Flink SQL client errors).
ERROR_PATTERNS=('[ERROR]' 'Could not execute SQL statement')

keep=""; build=1; steps=()
for arg in "$@"; do
  case "$arg" in
    --keep) keep=1 ;;
    --no-build) build="" ;;
    -h|--help) sed -n '2,19p' "$0"; exit 0 ;;
    -*) echo "unknown option: $arg" >&2; exit 2 ;;
    *) steps+=("$arg") ;;
  esac
done
[ ${#steps[@]} -gt 0 ] || read -ra steps <<<"$STEPS"

export COMPOSE_PROJECT_NAME=${COMPOSE_PROJECT_NAME:-proto-confluent-demo-verify}
export CAST_FAST=1
STEP_TIMEOUT=${STEP_TIMEOUT:-300}
OUT=.verify
TIMEOUT=()
if command -v timeout >/dev/null; then TIMEOUT=(timeout "$STEP_TIMEOUT")
elif command -v gtimeout >/dev/null; then TIMEOUT=(gtimeout "$STEP_TIMEOUT"); fi

fail=0
problem() {
  echo "FAIL $*"
  step_failed=1
  [ -z "${GITHUB_ACTIONS:-}" ] || echo "::error title=Docs demo::$*"
  fail=1
}

# Every committed SQL file must be run by a cast or a step, so a new snippet cannot go unchecked.
# sql/orders.sql is generated by the quickstart cast.
for f in sql/*.sql; do
  name=${f#sql/}
  [ "$name" != orders.sql ] || continue
  if ! grep -qF "sql/$name" casts/*.sh && [[ " $STEPS " != *" $name "* ]]; then
    problem "$f is not run by any cast or verify.sh step"
  fi
done
for step in "${steps[@]}"; do
  [ -x "casts/$step.sh" ] || [ -f "sql/$step" ] || { echo "no such step: $step" >&2; exit 2; }
  [ -f "expected/$step.txt" ] || problem "expected/$step.txt is missing: every step needs its expected output"
done
for cast in casts/*.sh; do
  name=$(basename "$cast" .sh)
  [ "$name" = _lib ] || [[ " $STEPS " == *" $name "* ]] || problem "$cast is not a verify.sh step"
done

cleanup() {
  if [ -n "$keep" ]; then
    echo "stack left running; stop it with: docker compose -p $COMPOSE_PROJECT_NAME down -v"
  else
    docker compose down -v >/dev/null 2>&1 || true
  fi
}
trap cleanup EXIT

start_stack() {
  docker compose down -v >/dev/null 2>&1 || true
  docker compose up -d --quiet-pull
  echo "waiting for Schema Registry and a Flink TaskManager..."
  local deadline=$((SECONDS + 180))
  until docker compose exec -T schema-registry curl -sf localhost:8081/subjects >/dev/null 2>&1 &&
    docker compose exec -T jobmanager curl -sf localhost:8081/taskmanagers 2>/dev/null | grep -q '"id"'; do
    if [ $SECONDS -ge $deadline ]; then
      docker compose logs --tail 50
      echo "FAIL demo stack not ready after 180s"
      exit 1
    fi
    sleep 2
  done
}

# Prints the first line of $1 (expected, comments and blank lines skipped) not found in $2 after the
# previous one matched (several may match one line); prints nothing when all are found in order.
# Lines are plain substrings.
first_missing() {
  awk 'NR == FNR { if ($0 !~ /^(#|$)/) want[n++] = $0; next }
       { while (i < n && index($0, want[i])) i++ }
       END { if (i < n) print want[i] }' "$1" "$2"
}

[ -z "$build" ] || ./setup.sh
rm -rf "$OUT"; mkdir -p "$OUT"
started_stack=""
for step in "${steps[@]}"; do
  if [ -z "$started_stack" ] || [[ " $FRESH_STACK_STEPS " == *" $step "* ]]; then
    start_stack; started_stack=1
  fi
  started=$SECONDS
  if [ -x "casts/$step.sh" ]; then cmd=("./casts/$step.sh"); else cmd=(bin/flink-sql "sql/$step"); fi
  status=0
  # Strip colours so the expected lines match plain text.
  ${TIMEOUT[@]+"${TIMEOUT[@]}"} "${cmd[@]}" 2>&1 | sed $'s/\x1b\\[[0-9;]*m//g' >"$OUT/$step.out" || status=$?
  step_failed=""
  [ "$status" -eq 0 ] || problem "$step: exited with status $status (124 means it timed out after ${STEP_TIMEOUT}s)"
  for pattern in "${ERROR_PATTERNS[@]}"; do
    if grep -qF -- "$pattern" "$OUT/$step.out"; then problem "$step: output contains '$pattern'"; fi
  done
  if [ -f "expected/$step.txt" ]; then
    missing=$(first_missing "expected/$step.txt" "$OUT/$step.out")
    [ -z "$missing" ] || problem "$step: expected line not found (in order): $missing"
  fi
  if [ -n "$step_failed" ]; then
    echo "---- $step output ($OUT/$step.out) ----"; cat "$OUT/$step.out"; echo "----"
  else
    echo "ok   $step ($((SECONDS - started))s)"
  fi
done

if [ "$fail" -ne 0 ]; then echo "docs demo verification FAILED"; exit 1; fi
echo "docs demo verification passed: ${steps[*]}"
